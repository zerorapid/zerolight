"use client";

import React, { useState, useEffect } from "react";
import Link from "next/link";
import { ZeroLightProvider, DEFAULT_TOKENS, ZeroLightTokens } from "@/components/zerolight";
import { SaasTemplateStage, SaasTemplateKey } from "@/components/zerolight/studio/saas-template-stage";
import { TokenStudioSidebar } from "@/components/zerolight/studio/token-studio-sidebar";
import { Button } from "@/components/zerolight/atoms/button";
import { Code2, Printer, Share2, Download, Check, ChevronLeft } from "lucide-react";

export default function StudioIsolatedPage() {
  const [tokens, setTokens] = useState<ZeroLightTokens>(DEFAULT_TOKENS);
  const [activeSaasTemplate, setActiveSaasTemplate] = useState<SaasTemplateKey>("zerolight_core");
  const [brandName, setBrandName] = useState("ZeroLight OS");
  const [brandMark, setBrandMark] = useState("ZL");
  const [brandLogoUrl, setBrandLogoUrl] = useState<string | null>(null);
  const [selectedIconMark, setSelectedIconMark] = useState("shield");
  const [isExportOpen, setIsExportOpen] = useState(false);
  const [copiedLink, setCopiedLink] = useState(false);

  // Restore theme from URL Hash on page load (#theme=...)
  useEffect(() => {
    if (typeof window === "undefined") return;
    try {
      const hash = window.location.hash;
      if (hash.startsWith("#theme=")) {
        const encoded = hash.slice(7);
        const jsonStr = decodeURIComponent(atob(encoded));
        const data = JSON.parse(jsonStr);
        if (data.tokens) setTokens((prev) => ({ ...prev, ...data.tokens }));
        if (data.brandName) setBrandName(data.brandName);
        if (data.brandMark) setBrandMark(data.brandMark);
        if (data.selectedIconMark) setSelectedIconMark(data.selectedIconMark);
      }
    } catch (e) {
      console.warn("Could not parse theme from URL hash:", e);
    }
  }, []);

  const handleUpdateTokens = (updates: Partial<ZeroLightTokens>) => {
    setTokens((prev) => ({ ...prev, ...updates }));
  };

  const handleShareTheme = () => {
    if (typeof window === "undefined") return;
    try {
      const payload = {
        tokens,
        brandName,
        brandMark,
        selectedIconMark,
      };
      const encoded = btoa(encodeURIComponent(JSON.stringify(payload)));
      const shareUrl = `${window.location.origin}${window.location.pathname}#theme=${encoded}`;
      navigator.clipboard.writeText(shareUrl);
      setCopiedLink(true);
      setTimeout(() => setCopiedLink(false), 2200);
    } catch (e) {
      console.error("Failed to copy share URL", e);
    }
  };

  const handleDownloadConfig = () => {
    const configContent = `// ZeroLight Design System Runtime Configuration
// Auto-generated by ZeroLight Visual Studio Dock

export const zeroLightConfig = {
  brand: {
    name: ${JSON.stringify(brandName)},
    mark: ${JSON.stringify(brandMark)},
    icon: ${JSON.stringify(selectedIconMark)},
  },
  tokens: ${JSON.stringify(tokens, null, 2)},
} as const;

export default zeroLightConfig;
`;
    const blob = new Blob([configContent], { type: "text/typescript;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "zerolight.config.ts";
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <ZeroLightProvider tokens={tokens} updateTokens={handleUpdateTokens}>
      <div className="h-screen w-screen overflow-hidden flex flex-col bg-[#FAFAFA] text-zinc-950 font-sans select-none print:h-auto print:w-auto print:overflow-visible">
        {/* ══════════════════════════════════════════════════════════════════════
            CLEAN APP HEADER (ZERO CLUTTER: Title & Status + ZeroLight Actions)
           ══════════════════════════════════════════════════════════════════════ */}
        <header className="h-14 px-6 border-b border-zinc-200/80 bg-white flex items-center justify-between shrink-0 z-20 print:hidden">
          <div className="flex items-center gap-3">
            <div className="flex flex-col">
              <span className="font-bold text-sm text-zinc-900 tracking-tight">Visual Studio Dock</span>
              <span className="text-[11px] text-zinc-500 font-medium">Runtime Token &amp; Design System Engine</span>
            </div>
            <span className="ml-2 px-2 py-0.5 rounded-full text-[10px] font-semibold bg-emerald-50 text-emerald-700 border border-emerald-200/60 hidden xl:inline-block">
              Live Global Hierarchy
            </span>
          </div>

          {/* Central Template & Showcase View Switcher */}
          <div className="hidden md:flex items-center p-1 rounded-xl bg-slate-100 border border-slate-200/80 gap-1">
            {[
              { id: "zerolight_core", label: "Spec Catalog" },
              { id: "hero_showcase", label: "Hero & Bento" },
              { id: "unified_enterprise", label: "Enterprise Console" },
              { id: "customer_crm", label: "CRM Pipeline" },
              { id: "metric_deck", label: "SaaS Metrics" },
            ].map((tmpl) => (
              <button
                key={tmpl.id}
                type="button"
                onClick={() => setActiveSaasTemplate(tmpl.id as SaasTemplateKey)}
                className={`px-2.5 py-1 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
                  activeSaasTemplate === tmpl.id
                    ? "bg-white text-slate-900 shadow-xs"
                    : "text-slate-500 hover:text-slate-800"
                }`}
              >
                {tmpl.label}
              </button>
            ))}
          </div>

          {/* Action Buttons using REAL ZeroLight Button Primitive */}
          <div className="flex items-center gap-2">
            <Link href="/?tab=tools">
              <Button
                variant="outline"
                size="sm"
                iconLeft={<ChevronLeft className="w-3.5 h-3.5" />}
              >
                Tools
              </Button>
            </Link>
            <Button
              variant="outline"
              size="sm"
              onClick={handleShareTheme}
              iconLeft={copiedLink ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Share2 className="w-3.5 h-3.5" />}
            >
              {copiedLink ? "Link Copied!" : "Share Theme"}
            </Button>
            <Button
              variant="outline"
              size="sm"
              onClick={handleDownloadConfig}
              iconLeft={<Download className="w-3.5 h-3.5" />}
            >
              Download Config
            </Button>
            <Button
              variant="outline"
              size="sm"
              onClick={() => window.print()}
              iconLeft={<Printer className="w-3.5 h-3.5" />}
            >
              Download PDF
            </Button>
            <Button
              variant="primary"
              size="sm"
              onClick={() => setIsExportOpen(true)}
              iconLeft={<Code2 className="w-3.5 h-3.5" />}
            >
              Export Code
            </Button>
          </div>
        </header>

        {/* ══════════════════════════════════════════════════════════════════════
            ISOLATED VISUAL STUDIO DOCK WORKSPACE
            Left: Real ZeroLight Assembled Component Stage
            Right: 340px Real ZeroLight Dogfooded Token Studio Sidebar
           ══════════════════════════════════════════════════════════════════════ */}
        <div className="w-full flex-1 min-h-0 flex flex-col lg:flex-row items-stretch overflow-hidden print:overflow-visible print:h-auto print:block">
          {/* Left Column: Visual Studio Dock Spec Stage */}
          <div className="flex-1 min-w-0 flex flex-col h-full bg-[#FAFAFA] overflow-hidden print:overflow-visible print:h-auto print:block">
            <SaasTemplateStage
              activeTemplate={activeSaasTemplate}
              brandName={brandName}
              brandMark={brandMark}
              brandLogoUrl={brandLogoUrl}
              selectedIconMark={selectedIconMark}
              className="h-full print:h-auto print:overflow-visible"
            />
          </div>

          {/* Right Column: 340px Docked Token Studio Sidebar */}
          <div className="w-full lg:w-[340px] shrink-0 h-full flex flex-col border-t lg:border-t-0 lg:border-l border-zinc-200/80 bg-white overflow-hidden shadow-xs print:hidden">
            <TokenStudioSidebar
              brandName={brandName}
              onBrandNameChange={setBrandName}
              brandMark={brandMark}
              onBrandMarkChange={setBrandMark}
              brandLogoUrl={brandLogoUrl}
              onBrandLogoUpload={setBrandLogoUrl}
              selectedIconMark={selectedIconMark}
              onSelectedIconMarkChange={setSelectedIconMark}
              exportOpen={isExportOpen}
              onExportOpenChange={setIsExportOpen}
              className="h-full"
            />
          </div>
        </div>
      </div>
    </ZeroLightProvider>
  );
}
